#!/bin/sh
# Generate the static Documentation section of the Pages site.
#
# Instead of linking out to the GitHub docs/ folder, the build system scans the
# real docs/ tree and renders every Markdown file to a self-contained,
# JavaScript-free HTML page using the same shared chrome and stylesheet as the
# Home, Download and RPR pages. The converter is tools/build/md2html.awk (pure
# awk: the Makefile forbids Python/Node in the production path).
#
# Layout (a flat tree so links never depend on the original subdirectories):
#   docs/index.html          directory listing of every document, by folder
#   docs/<NAME>/index.html    one rendered Markdown document
#   docs/<asset>              every non-Markdown file (csv, txt, ...) verbatim
#
# A flat <NAME>/index.html per document keeps the converter's rewritten links
# correct: relative ".md" links become "NAME/index.html" and same-directory
# assets become bare filenames, and every basename in docs/ is unique.
#
#   arguments:
#     docs_dir  absolute path to the repository docs/ tree (the input)
#     output    absolute path to the site docs/ directory to write
#
# All emitted URLs are relative; nothing here bakes in a Pages base path.
set -eu
[ "$#" = 2 ] || exit 2
docs=$1 output=$2
here=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
[ -d "$docs" ] || { echo "missing docs tree at $docs" >&2; exit 1; }
# shellcheck source=/dev/null
. "$here/site-common.sh"

mkdir -p "$output"

# doc_title <md-file>: first level-1 heading text, else the basename.
doc_title() {
    t=$(sed -n 's/^#[ \t]\{1,\}//p' "$1" 2>/dev/null | sed -n '1p')
    if [ -z "$t" ]; then
        base=${1##*/}
        t=${base%.md}
    fi
    printf '%s\n' "$t"
}

# Render every Markdown document to docs/<NAME>/index.html. Filenames must be
# plain so they are safe to place in a path and an href; anything unusual is
# rejected rather than emitted (matching the RPR filename discipline).
# Superpowers handoff/audit records are internal evidence, not public site
# documents; their relative links intentionally target the audit directory.
for md in $(find "$docs" -path "$docs/superpowers" -prune -o -name '*.md' -print | LC_ALL=C sort); do
    base=${md##*/}
    name=${base%.md}
    case $name in
        ''|*[!a-zA-Z0-9._-]*) echo 'unsafe docs filename' >&2; exit 1 ;;
    esac
    dir="$output/$name"
    mkdir -p "$dir"
    title=$(doc_title "$md")
    # Document pages sit one level deeper than the docs index (docs/NAME/),
    # so the shared chrome is reached with a ../ prefix relative to docs/.
    {
        site_page_begin "../../css/reliefos.css" "../../" \
            "$(printf '%s' "$title" | site_html_escape) &mdash; ReliefOS Documentation" \
            "ReliefOS Documentation"
        printf '<p class="breadcrumb"><a href="../index.html">Documentation</a> &rsaquo; %s</p>\n' \
            "$(printf '%s' "$name" | site_html_escape)"
        awk -f "$here/md2html.awk" "$md"
        site_page_end
    } > "$dir/index.html"
done

# Copy every non-Markdown asset (tables in .csv, plain .txt notes) verbatim so
# in-text links to them resolve. Basenames are unique across the tree.
for asset in $(find "$docs" -path "$docs/superpowers" -prune -o -type f ! -name '*.md' -print | LC_ALL=C sort); do
    fname=${asset##*/}
    case $fname in
        ''|*[!a-zA-Z0-9._-]*) continue ;;
    esac
    cp "$asset" "$output/$fname"
done

# --- documentation index ----------------------------------------------------
# A single page listing every rendered document grouped by its source folder,
# all derived from the real docs/ tree so the page cannot drift from it.
{
    site_page_begin "../css/reliefos.css" "../" \
        "ReliefOS Documentation" "Documentation"
    printf '<p class="subtitle">Project documentation, rendered from the source tree at build time.</p>\n'
    printf '<section>\n'
    printf '<p>These pages are generated by the ReliefOS build system from the '
    printf '<code>docs/</code> tree: every document is converted from Markdown to '
    printf 'static HTML with no JavaScript.</p>\n'
    printf '</section>\n'

    group=
    for md in $(find "$docs" -path "$docs/superpowers" -prune -o -name '*.md' -print | LC_ALL=C sort); do
        rel=${md#"$docs"/}
        if [ "$rel" = "$md" ]; then rel=$md; fi
        case $rel in
            */*) sub=${rel%/*} ;;
            *)   sub="(top level)" ;;
        esac
        if [ "$sub" != "$group" ]; then
            if [ -n "$group" ]; then printf '</ul>\n</section>\n'; fi
            group=$sub
            printf '<section>\n<h2>%s</h2>\n<ul>\n' "$(printf '%s' "$group" | site_html_escape)"
        fi
        base=${rel##*/}
        name=${base%.md}
        title=$(doc_title "$md")
        printf '<li><a href="%s/index.html">%s</a></li>\n' \
            "$(printf '%s' "$name" | site_html_escape)" \
            "$(printf '%s' "$title" | site_html_escape)"
    done
    if [ -n "$group" ]; then printf '</ul>\n</section>\n'; fi
    site_page_end
} > "$output/index.html"
